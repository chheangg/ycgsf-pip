#!/usr/bin/env python3
"""Copy the pen.dev design's shaders (design/shaders/*.glsl) into the app as frontend/shaders.js.

The app runs the exact same GLSL as the design (voice wave, scan line, cursor), so the animations match.
Run after any shader changes in pen.dev:   python3 tools/export_shaders.py
tools/check_design.py fails if frontend/shaders.js is out of date.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent


def build() -> str:
    shaders = {p.stem: p.read_text() for p in sorted((root / "design/shaders").glob("*.glsl"))}
    body = ",\n".join(f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in shaders.items())
    return ("// Generated by tools/export_shaders.py from design/shaders/*.glsl (the pen.dev design). Do not edit.\n"
            f"const SHADERS = {{\n{body},\n}};\n")


if __name__ == "__main__":
    (root / "frontend/shaders.js").write_text(build())
    print("wrote frontend/shaders.js")
